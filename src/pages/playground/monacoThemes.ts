export function registerMonacoThemes(monaco: typeof Monaco) {
  for (const [themeId, themeData] of Object.entries(MONACO_THEMES)) {
    try {
      monaco.editor.defineTheme(themeId, themeData);
    } catch (e) {
      console.warn(`Failed to register Monaco theme ${themeId}:`, e);
    }
  }
}

export function configureMonacoLanguages(monaco: typeof Monaco) {
  try {
    // Configure TypeScript compiler options with JSX/TSX support
    monaco.languages.typescript.typescriptDefaults.setCompilerOptions({
      target: monaco.languages.typescript.ScriptTarget.ES2022,
      allowNonTextFiles: true,
      noLib: false,
      alwaysStrict: false,
      allowJs: true,
      jsx: monaco.languages.typescript.JsxEmit.ReactJSX,
      moduleResolution: monaco.languages.typescript.ModuleResolutionKind.NodeJs,
      allowSyntheticDefaultImports: true,
    });

    // Configure JavaScript compiler options with JSX support
    monaco.languages.typescript.javascriptDefaults.setCompilerOptions({
      target: monaco.languages.typescript.ScriptTarget.ES2022,
      allowNonTextFiles: true,
      noLib: false,
      alwaysStrict: false,
      allowJs: true,
      jsx: monaco.languages.typescript.JsxEmit.ReactJSX,
    });

    // Suppress false diagnostic errors for external modules while maintaining syntax validation
    monaco.languages.typescript.javascriptDefaults.setDiagnosticsOptions({
      noSemanticValidation: true,
      noSyntaxValidation: false,
      noSuggestionDiagnostics: true,
    });

    monaco.languages.typescript.typescriptDefaults.setDiagnosticsOptions({
      noSemanticValidation: true,
      noSyntaxValidation: false,
      noSuggestionDiagnostics: true,
    });
  } catch (e) {
    console.warn("Failed to configure Monaco language compiler options:", e);
  }
}
